// Regenerate the precomputed reference runs shown in the comparison table.
// Runs the six built-in strategies for the 12 oz can (standard mesh) in
// parallel child processes and writes src/ui/referenceRuns.js.
//   node tools/make-reference.mjs [resolution]
import { fork } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CrushScenario } from '../src/physics/scenario.js';
import { STRATEGIES, strategyParams } from '../src/sim/strategies.js';

if (process.argv[2] === '--child') {
  process.on('message', ({ params }) => {
    const sc = new CrushScenario(params);
    while (!sc.advance(500)) { /* run */ }
    const h = sc.history;
    process.send({ summary: sc.summary(), d: h.d.map((v) => v * 1000), F: h.F });
    process.exit(0);
  });
} else {
  const res = process.argv[2] || 'standard';
  const self = fileURLToPath(import.meta.url);
  const t0 = Date.now();
  const results = await Promise.all(STRATEGIES.map((s) => new Promise((resolve, reject) => {
    const params = strategyParams(s, { resolution: res });
    const child = fork(self, ['--child']);
    child.on('message', (m) => resolve({ s, params, ...m }));
    child.on('error', reject);
    child.send({ params });
  })));
  const ds = (d, F, max = 400) => {
    const step = Math.max(1, Math.ceil(d.length / max));
    const dd = [], ff = [];
    for (let i = 0; i < d.length; i += step) { dd.push(+d[i].toFixed(2)); ff.push(Math.round(F[i] * 10) / 10); }
    return { d: dd, F: ff };
  };
  const out = results.map(({ s, params, summary: m, d, F }) => {
    const c = ds(d, F);
    return {
      name: s.name, res,
      params,
      d: c.d, F: c.F,
      stats: {
        initialPeak: m.initialPeak, initialPeakAt: m.initialPeakAt === null ? null : m.initialPeakAt * 1000,
        peakForce: m.peakForce, peakAt: m.peakAt * 1000, meanForce: m.meanForce, work: m.work, travel: m.travel * 1000,
        finalHeight: m.finalHeight * 1000, initialHeight: m.initialHeight * 1000, volumeReduction: m.volumeReduction,
      },
    };
  });
  const js = `// Precomputed reference runs (${res} mesh, 12 oz can, default settings).\n// Generated by tools/make-reference.mjs on ${new Date().toISOString().slice(0, 10)}; do not edit by hand.\nexport const REFERENCE_RUNS = ${JSON.stringify(out)};\n`;
  writeFileSync(new URL('../src/ui/referenceRuns.js', import.meta.url), js);
  for (const r of out) console.log(r.name.padEnd(36), 'start', Math.round(r.stats.initialPeak || r.stats.peakForce), 'N  peak', Math.round(r.stats.peakForce), 'N  work', r.stats.work.toFixed(1), 'J  final', r.stats.finalHeight.toFixed(0), 'mm');
  console.log(`done in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
